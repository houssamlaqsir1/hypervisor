/**
 * Interface language: English or French.
 *
 * Keys are stable identifiers rather than English sentences, so rewording
 * the English copy never silently orphans a French translation — the pair
 * stays linked by the key. `en` is written out in full for the same reason:
 * both languages sit side by side in one file, which is what makes a
 * missing or stale translation visible instead of invisible.
 *
 * Scope note: alert *messages* ("Car on track 'X' — emergency stop
 * required") are composed by the backend's correlation rules and stored on
 * the alert, so they arrive already written and are not translated here.
 * Everything the interface itself says — navigation, headings, labels,
 * buttons, severities, statuses, alert type names — is.
 */

