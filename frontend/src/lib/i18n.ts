const DICTS: Record<Language, Dict> = { en, fr }

let current: Language = 'en'
const listeners = new Set<() => void>()

/**
 * Looks up a key in the active language.
 *
 * Falls back to English, then to the key itself — a missing translation
 * should degrade to readable English, never to a blank space in the middle
 * of the interface.
 *
 * @param vars values for `{placeholder}` slots in the string
 */
/** Signature of {@link t}, for helpers that take the translator as a parameter. */
export type Translate = (key: string, vars?: Record<string, string | number>) => string

export function t(key: string, vars?: Record<string, string | number>): string {
  const raw = DICTS[current][key] ?? en[key] ?? key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  )
}

export function getLanguage(): Language {
  return current
}

export function setLanguage(next: Language) {
  if (next === current) return
  current = next
  document.documentElement.lang = next
  const prefs = loadPrefs()
  savePrefs({ ...prefs, language: next })
  for (const listener of listeners) listener()
}

/** Applies the stored choice at boot, before the first render. */
export function initLanguage() {
  current = loadPrefs().language
  document.documentElement.lang = current
}

export function subscribeLanguage(listener: () => void): () => void {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

/** Snapshot for {@link useT} — changes identity whenever the language does. */
export function languageSnapshot(): Language {
  return current
}
